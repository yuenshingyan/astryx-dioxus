import assert from 'node:assert/strict';
import {withTarget} from './card_metrics.mjs';

await withTarget(async ({send, evaluate, waitFor, exceptions}) => {
  await send('Network.enable');
  await send('Network.setBlockedURLs', {urls: ['https://*']});
  await send('Page.navigate', {url: process.env.SHOWCASE_URL ?? 'http://127.0.0.1:8284'});
  const frame = "document.getElementById('overflow-list-frame')";
  const names = `Array.from(${frame}?.querySelectorAll('.astryx-overflow-list__row button') ?? [], node => node.textContent.trim())`;
  const exact = labels => `JSON.stringify(${names}) === ${JSON.stringify(JSON.stringify(labels))}`;
  const labels = ['Edit', 'Duplicate', 'Share', 'Archive', 'Delete'];
  const report = "document.getElementById('overflow-list-report')?.textContent.trim()";
  const expectReport = text => `${report} === ${JSON.stringify(text)}`;
  const settle = () => evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))');
  await waitFor(exact(labels));
  await evaluate('document.fonts.ready.then(() => true)');
  await settle();
  assert.equal(await evaluate(report), 'Reports: 0. Hidden: none');
  await evaluate(`${frame}.style.width = '170px'`);
  await waitFor(`${names}.at(-1)?.startsWith('+')`);
  const collapsed = await evaluate(names);
  assert.ok(collapsed.length < 5);
  const visibleCount = collapsed.length - 1;
  assert.deepEqual(collapsed.slice(0, -1), labels.slice(0, visibleCount));
  assert.equal(collapsed.at(-1), `+${6 - collapsed.length} more`);
  const {nodes} = await send('Accessibility.getFullAXTree');
  assert.ok(nodes.some(node => !node.ignored && node.role?.value === 'button' && node.name?.value === collapsed.at(-1)));
  assert.equal(nodes.filter(node => !node.ignored && node.role?.value === 'button' && node.name?.value === collapsed.at(-1)).length, 1);
  assert.ok(await evaluate(`(() => { const row = ${frame}.querySelector('.astryx-overflow-list__row'); return row.lastElementChild.getBoundingClientRect().right <= row.getBoundingClientRect().right + 1; })()`));
  assert.ok(await evaluate(`${frame}.querySelector('[aria-hidden=true][inert]') !== null`));
  const hidden = ordered => ordered.slice(visibleCount).map((label, offset) => `${visibleCount + offset}: ${label}`).join(', ');
  const firstReport = `Reports: 1. Hidden: ${hidden(labels)}`;
  await waitFor(expectReport(firstReport));
  // Force observer delivery without changing the final measured set.
  await evaluate(`${frame}.style.width = '169.99px'`);
  await settle();
  assert.equal(await evaluate(report), firstReport);

  const reordered = ['Edit', 'Duplicate', 'Share', 'Delete', 'Archive'];
  await evaluate(`Array.from(document.querySelectorAll('#overflow-list-examples button')).find(node => node.textContent.trim() === 'Swap last two actions').click()`);
  await waitFor(expectReport(`Reports: 2. Hidden: ${hidden(reordered)}`));
  assert.deepEqual(await evaluate(names), collapsed);
  await evaluate(`${frame}.style.width = '400px'`);
  await waitFor(exact(reordered));
  await waitFor(expectReport('Reports: 3. Hidden: none'));
  await settle();
  assert.equal(await evaluate(report), 'Reports: 3. Hidden: none');
  assert.deepEqual(exceptions, []);
  console.log('OverflowList: shrink, unchanged resize, keyed reorder, grow-back, inert measurement and accessible indicator passed');
});

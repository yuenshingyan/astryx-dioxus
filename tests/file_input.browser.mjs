import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {withTarget} from './card_metrics.mjs';

await withTarget(async ({send, evaluate, waitFor, exceptions}) => {
  await send('Network.enable');
  await send('Network.setBlockedURLs', {urls: ['https://*']});
  await send('Page.navigate', {url: process.env.SHOWCASE_URL ?? 'http://127.0.0.1:8324'});
  const selector = '#file-input-examples input[name=attachment]';
  const input = `document.querySelector('${selector}')`;
  await waitFor(input);
  assert.equal(await evaluate(`${input}.labels[0].textContent.trim()`), 'Upload file ∙ Required');
  assert.ok(await evaluate(`${input}.validity.valueMissing && ${input}.accept === '.txt'`));
  assert.equal(await evaluate(`document.getElementById(${input}.getAttribute('aria-describedby')).textContent`), 'Choose a local file. This demo does not upload it.');
  const {root} = await send('DOM.getDocument');
  const {nodeId} = await send('DOM.querySelector', {nodeId: root.nodeId, selector});
  await send('DOM.setFileInputFiles', {nodeId, files: [fileURLToPath(new URL('./fixtures/file-input/sample.txt', import.meta.url))]});
  const count = "document.getElementById('file-input-count').textContent";
  await waitFor(`${count} === '1 selected'`);
  assert.ok(await evaluate(`${input}.validity.valid && new FormData(${input}.form).get('attachment').name === 'sample.txt'`));
  assert.ok(await evaluate(`${input}.form.elements.attachments.multiple && !new FormData(${input}.form).has('unavailable')`));
  const attachments = `${input}.form.elements.attachments`;
  assert.ok(await evaluate(`${attachments}.validity.valid && ${attachments}.getAttribute('aria-invalid') === 'true'`));
  assert.deepEqual(await evaluate(`${attachments}.getAttribute('aria-describedby').split(' ').map(id => document.getElementById(id).textContent.trim())`), ['Use the project’s current documents.', 'The previous attachments are out of date.']);
  assert.equal(await evaluate(`document.getElementById('attachment-status').dataset.variant`), 'detached');
  const {nodes} = await send('Accessibility.getFullAXTree');
  assert.ok(nodes.some(node => !node.ignored && node.name?.value === 'Attachments' && node.description?.value.includes('The previous attachments are out of date.')));
  const toggle = "document.getElementById('file-input-toggle-loading')";
  await send('Page.bringToFront');
  await waitFor('document.hasFocus()');
  await evaluate(`${input}.focus(); ${toggle}.click()`);
  await waitFor(`${input}.getAttribute('aria-busy') === 'true'`);
  assert.ok(await evaluate(`${input}.parentElement.querySelector('.astryx-spinner[aria-hidden=true]') && document.activeElement === ${input}`));
  assert.deepEqual(await evaluate(`[new MouseEvent('click', {bubbles:true,cancelable:true}), new DragEvent('drop', {bubbles:true,cancelable:true,dataTransfer:new DataTransfer()})].map(event => ${input}.dispatchEvent(event))`), [false, false]);
  const keydownResults = `['Enter', ' ', 'Tab'].map(key => ${input}.dispatchEvent(new KeyboardEvent('keydown', {key, bubbles:true, cancelable:true})))`;
  assert.deepEqual(await evaluate(keydownResults), [false, false, true]);
  assert.ok(await evaluate(`${input}.validity.valid && new FormData(${input}.form).get('attachment').name === 'sample.txt'`));
  await evaluate(`${toggle}.click()`);
  await waitFor(`!${input}.hasAttribute('aria-busy') && !${input}.parentElement.querySelector('.astryx-spinner')`);
  assert.deepEqual(await evaluate(keydownResults), [true, true, true]);
  await evaluate(`${input}.form.reset()`);
  assert.ok(await evaluate(`${input}.files.length === 0 && ${input}.validity.valueMissing`));
  assert.deepEqual(exceptions, []);
  console.log('FileInput: associated label and description, required validity, selection and form reset, and form behavior passed');
});

import assert from 'node:assert/strict';
import {withTarget} from './card_metrics.mjs';

await withTarget(async ({send, evaluate, waitFor, exceptions}) => {
  await send('Network.enable');
  await send('Network.setBlockedURLs', {urls: ['https://*']});
  await send('Page.navigate', {url: process.env.SHOWCASE_URL ?? 'http://127.0.0.1:8327'});
  const form = "document.querySelector('#date-time-input-examples form')";
  const date = `${form}.querySelector('input[type=date]')`;
  const time = `${form}.querySelector('input[type=time]')`;
  const output = "document.getElementById('date-time-input-value').textContent";
  const change = (input, value) => evaluate(`${input}.value = ${JSON.stringify(value)}; ${input}.dispatchEvent(new Event('change', {bubbles:true}))`);
  await waitFor(`${form} && ${date} && ${time}`);
  assert.equal(await evaluate(`${date}.labels[0].textContent`), 'Meeting time');
  assert.equal(await evaluate(`${time}.getAttribute('aria-label')`), 'Time');
  assert.deepEqual(await evaluate(`[${date}.min, ${date}.max, ${time}.min, ${time}.max]`), ['2024-02-29', '2024-03-02', '', '']);
  await change(time, '13:00');
  assert.equal(await evaluate(output), 'No date and time selected');
  await change(date, '2024-02-29');
  await waitFor(`${output} === '2024-02-29T14:25'`);
  assert.deepEqual(await evaluate(`Array.from(new FormData(${form}))`), [['meeting', '2024-02-29T14:25']]);
  assert.deepEqual(await evaluate(`[${time}.min, ${time}.max, ${time}.validity.valid]`), ['14:25', '', true]);
  assert.ok(await evaluate(`${time}.value = '14:24'; ${time}.validity.rangeUnderflow`));
  await change(time, '16:30');
  await waitFor(`${output} === '2024-02-29T16:30'`);
  await change(date, '2024-03-02');
  await waitFor(`${output} === '2024-03-02T15:00' && ${time}.max === '15:00'`);
  assert.deepEqual(await evaluate(`[${time}.min, ${time}.validity.valid]`), ['', true]);
  assert.ok(await evaluate(`${time}.value = '15:01'; ${time}.validity.rangeOverflow`));
  await change(date, '');
  await waitFor(`${output} === 'No date and time selected' && ${time}.value === ''`);
  await change(date, '2024-03-01');
  await waitFor(`${output}.startsWith('2024-03-01T')`);
  assert.match(await evaluate(output), /^2024-03-01T\d{2}:\d{2}$/);
  assert.deepEqual(await evaluate(`[${time}.min, ${time}.max]`), ['', '']);
  const clear = `${form}.querySelector('button[aria-label="Clear Meeting time"]')`;
  await waitFor(clear);
  await send('Page.bringToFront');
  await waitFor('document.hasFocus()');
  const toggle = "document.getElementById('date-time-input-toggle-loading')";
  const spinner = `${form}.querySelector('.astryx-date-time-input__loading .astryx-spinner[aria-hidden=true]')`;
  const committed = await evaluate(output);
  await evaluate(`${date}.focus(); ${toggle}.click()`);
  await waitFor(`${date}.getAttribute('aria-busy') === 'true' && ${time}.getAttribute('aria-busy') === 'true' && ${spinner} && !${clear}`);
  assert.ok(await evaluate(`${date}.readOnly && ${time}.readOnly && document.activeElement === ${date}`));
  assert.deepEqual(await evaluate(`Array.from(new FormData(${form}))`), [['meeting', committed]]);
  await change(date, '2024-03-02');
  await change(time, committed.endsWith('T10:00') ? '11:00' : '10:00');
  assert.equal(await evaluate(output), committed);
  assert.deepEqual(await evaluate(`Array.from(new FormData(${form}))`), [['meeting', committed]]);
  await evaluate(`${date}.value = ${JSON.stringify(committed.slice(0, 10))}; ${time}.value = ${JSON.stringify(committed.slice(11))}`);
  await evaluate(`${toggle}.click()`);
  await waitFor(`!${date}.readOnly && !${time}.readOnly && !${date}.hasAttribute('aria-busy') && !${time}.hasAttribute('aria-busy') && !${spinner} && ${clear}`);
  await evaluate(`window.segmentEvents = 0; for (const segment of [${date}, ${time}]) for (const type of ['focus','input','change']) segment.addEventListener(type, () => window.segmentEvents++); ${clear}.focus()`);
  for (const type of ['keyDown', 'keyUp']) await send('Input.dispatchKeyEvent', {type, key:'Enter', code:'Enter', windowsVirtualKeyCode:13, ...(type === 'keyDown' ? {text:'\r'} : {})});
  await waitFor(`${output} === 'No date and time selected' && ${date}.value === '' && ${time}.value === '' && !${clear}`);
  assert.equal(await evaluate('window.segmentEvents'), 0);
  assert.deepEqual(await evaluate(`Array.from(new FormData(${form}))`), [['meeting', '']]);
  const example = "document.getElementById('date-time-input-status-example')";
  const descriptions = ['Choose an available review slot.', 'This review slot is already booked.'];
  for (const type of ['date', 'time']) {
    const segment = `${example}.querySelector('input[type=${type}]')`;
    assert.ok(await evaluate(`${segment}.validity.valid && ${segment}.getAttribute('aria-invalid') === 'true'`));
    assert.deepEqual(await evaluate(`${segment}.getAttribute('aria-describedby').split(' ').map(id => document.getElementById(id).textContent.trim())`), descriptions);
  }
  assert.equal(await evaluate(`${example}.querySelectorAll('.astryx-field-status').length`), 1);
  assert.equal(await evaluate(`document.getElementById('review-slot-status').dataset.variant`), 'detached');
  const {nodes} = await send('Accessibility.getFullAXTree');
  for (const name of ['Review date', 'Review time']) {
    assert.ok(nodes.some(node => !node.ignored && node.name?.value === name && node.description?.value.includes(descriptions[1])));
  }
  assert.deepEqual(exceptions, []);
  console.log('DateTimeInput: native names, time-first draft, combined form value, clearing and date-first default passed');
});

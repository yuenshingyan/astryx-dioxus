import assert from 'node:assert/strict';
import {withTarget} from './card_metrics.mjs';

await withTarget(async ({send, evaluate, waitFor, exceptions}) => {
  await send('Network.enable');
  await send('Network.setBlockedURLs', {urls: ['https://*']});
  await send('Page.addScriptToEvaluateOnNewDocument', {source: `
    Object.defineProperty(navigator, 'clipboard', {value: {async writeText(text) {
      if (window.rejectCodeCopy) throw new Error('Clipboard denied');
      window.copiedCode = text;
    }}});
  `});
  await send('Page.navigate', {url: process.env.SHOWCASE_URL ?? 'http://127.0.0.1:8309'});
  const block = `document.querySelector('#code-block-examples')`;
  const pre = `${block}.querySelector('pre')`;
  const button = `${block}.querySelector('button')`;
  const status = `${block}.querySelector('[data-code-block-status][role=status]')`;
  const error = `${block}.querySelector('[data-code-block-error][role=alert]')`;
  await waitFor(`${block} && ${button}`);
  assert.deepEqual(await evaluate(`[${status}.textContent, ${error}.textContent]`), ['', '']);
  await evaluate(`window.codeCopyRegions = [${status}, ${error}]`);
  assert.equal(await evaluate(`${pre}.tabIndex`), 0);
  assert.equal(await evaluate(`${pre}.querySelector('code').textContent.split('\\n').length`), 13);
  assert.equal(await evaluate(`${pre}.querySelectorAll('[aria-hidden=true][data-number]').length`), 13);
  await evaluate(`${button}.click()`);
  await waitFor(`${status}.textContent === 'Copied code' && ${error}.textContent === ''`);
  assert.equal(await evaluate('window.copiedCode'), await evaluate(`${pre}.querySelector('code').textContent`));
  assert.ok((await evaluate('window.copiedCode')).includes('fetch(`/api/users/${id}`)'));
  await evaluate(`window.rejectCodeCopy = true; ${button}.click()`);
  await waitFor(`${error}.textContent === 'Could not copy code' && ${status}.textContent === ''`);
  await evaluate(`window.rejectCodeCopy = false; ${button}.click()`);
  await waitFor(`${status}.textContent === 'Copied code' && ${error}.textContent === ''`);
  assert.ok(await evaluate(`${status} === window.codeCopyRegions[0] && ${error} === window.codeCopyRegions[1]`));
  const diff = `document.getElementById('code-block-diff-example')`;
  const source = '--- a/settings.rs\n+++ b/settings.rs\n@@ -1,2 +1,2 @@\n-const RETRIES: u8 = 2;\n+const RETRIES: u8 = 3;\n const DELAY: u8 = 5;';
  assert.deepEqual(await evaluate(`Array.from(${diff}.querySelectorAll('[data-diff]'), el => el.dataset.diff)`), ['header', 'header', 'header', 'removed', 'added', 'context']);
  assert.equal(await evaluate(`${diff}.querySelector('code').textContent`), source);
  assert.ok(await evaluate(`getComputedStyle(${diff}.querySelector('[data-diff=added]')).backgroundColor !== getComputedStyle(${diff}.querySelector('[data-diff=removed]')).backgroundColor`));
  await evaluate(`window.rejectCodeCopy = false; ${diff}.querySelector('button').click()`);
  await waitFor(`${diff}.querySelector('[data-code-block-status][role=status]').textContent === 'Copied code'`);
  assert.equal(await evaluate('window.copiedCode'), source);
  const disclosure = `document.getElementById('code-block-disclosure-example')`;
  const toggle = `${disclosure}.querySelector('button[aria-expanded]')`;
  const actions = `${disclosure}.querySelector('.astryx-code-block__actions')`;
  const save = `${actions}.querySelector('button:first-child')`;
  const copy = `${actions}.querySelector('button:last-child')`;
  const region = `document.getElementById(${toggle}.getAttribute('aria-controls'))`;
  await send('Page.bringToFront');
  await waitFor('document.hasFocus()');
  await evaluate(`window.originalCodeRegion = ${region}; ${toggle}.focus()`);
  const press = async (key, code, windowsVirtualKeyCode, text) => {
    await send('Input.dispatchKeyEvent', {type:'keyDown', key, code, windowsVirtualKeyCode, text});
    await send('Input.dispatchKeyEvent', {type:'keyUp', key, code, windowsVirtualKeyCode});
  };
  await press(' ', 'Space', 32, ' ');
  await waitFor(`${toggle}.getAttribute('aria-expanded') === 'false' && ${region}.hidden && ${region}.getClientRects().length === 0 && document.activeElement === ${toggle}`);
  assert.deepEqual(await evaluate(`Array.from(${actions}.querySelectorAll('button'), el => el.textContent.trim())`), ['Save excerpt', 'Copy code']);
  await evaluate(`${save}.focus()`);
  await press('Enter', 'Enter', 13, '\r');
  await waitFor(`${save}.textContent.trim() === 'Saved' && ${region}.hidden && document.activeElement === ${save}`);
  await evaluate(`${copy}.click()`);
  await waitFor(`${disclosure}.querySelector('[data-code-block-status]').textContent === 'Copied code'`);
  assert.equal(await evaluate('window.copiedCode'), await evaluate(`${pre}.querySelector('code').textContent`));
  assert.ok(await evaluate(`${region}.hidden && window.originalCodeRegion === ${region}`));
  await evaluate(`${toggle}.focus()`);
  await press('Enter', 'Enter', 13, '\r');
  await waitFor(`${toggle}.getAttribute('aria-expanded') === 'true' && !${region}.hidden && window.originalCodeRegion === ${region}`);
  const corner = `document.querySelector('#code-block-corner-example .astryx-code-block')`;
  assert.ok(await evaluate(`!${corner}.querySelector('.astryx-code-block__header')`));
  assert.ok(await evaluate(`${corner}.querySelector('pre').getBoundingClientRect().right <= ${corner}.querySelector('.astryx-code-block__actions').getBoundingClientRect().left`));
  assert.deepEqual(await evaluate(`Array.from(${corner}.querySelectorAll('a,button'), el => el.textContent.trim())`), ['See full excerpt', 'Copy code']);
  const widthDemo = "document.getElementById('code-block-width-example')";
  const widths = `Array.from(${widthDemo}.querySelectorAll('.astryx-code-block'), el => el.getBoundingClientRect().width)`;
  assert.deepEqual(await evaluate(widths), [240, 360]);
  await evaluate(`${widthDemo}.style.inlineSize = '180px'`);
  assert.deepEqual(await evaluate(widths), [180, 180]);
  await evaluate(`${corner}.parentElement.style.inlineSize = '180px'; ${corner}.dir = 'rtl'`);
  assert.equal(await evaluate(`${corner}.getBoundingClientRect().width`), 180);
  assert.ok(await evaluate(`${corner}.querySelector('pre').getBoundingClientRect().left >= ${corner}.querySelector('.astryx-code-block__actions').getBoundingClientRect().right`));
  assert.deepEqual(exceptions, []);
  console.log('Code Block: line gutter, exact-source copy and failure status passed');
});
